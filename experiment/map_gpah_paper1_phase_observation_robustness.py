#!/usr/bin/env python3
"""Controlled robustness study for imperfect MMPP-phase observations.

The physical queueing sample path is generated by ``SparseMapPhEnv``. Only the
phase belief supplied to the gPAH forecast term changes. Observation errors use
a separate deterministic construction and therefore do not consume the
simulator RNG stream.
"""

from __future__ import annotations

import argparse
import json
import math
import os
from dataclasses import dataclass
from typing import Dict, List, Sequence

import matplotlib.pyplot as plt
import numpy as np

from map_gpah_paper1_common import (
    PAPER_COLORS,
    CaseSpec,
    RunConfig,
    SparseMapPhEnv,
    make_problem,
    mean_ci,
    policy_cases,
    policy_from_name,
    render_progress,
    simulate_policy_object,
    write_csv,
)


DEFAULT_CASE_IDS = (
    "low_contrast",
    "fast_mixing",
    "high_burst",
    "predictive_burst",
    "multi_state_burst",
    "alternating_hotspots",
)
DEFAULT_REGIMES = "oracle,posterior_0.10,posterior_0.25,posterior_0.50,delay_1,delay_3,stationary"


@dataclass(frozen=True)
class ObservationRegime:
    name: str
    kind: str
    contamination: float = 0.0
    delay: int = 0


def stationary_distribution(Q: np.ndarray) -> np.ndarray:
    matrix = Q.T.copy()
    matrix[-1, :] = 1.0
    rhs = np.zeros(Q.shape[0])
    rhs[-1] = 1.0
    return np.linalg.solve(matrix, rhs)


class BeliefForecastEnv(SparseMapPhEnv):
    """Expose an oracle, contaminated, delayed, or stationary phase belief."""

    def __init__(self, problem, seed: int, regime: ObservationRegime):
        super().__init__(problem, seed)
        self.base_seed = int(seed)
        self.arrival_rng = np.random.default_rng(self.base_seed + 100000000)
        self.phase_rng = np.random.default_rng(self.base_seed + 200000000)
        self.service_rng = np.random.default_rng(self.base_seed + 300000000)
        self.regime = regime
        self.phase_history: List[np.ndarray] = []
        self.stationary = [stationary_distribution(Q) for Q in problem.arrival_Q]

    def reset(self):
        self.rng = np.random.default_rng(self.base_seed)
        self.arrival_rng = np.random.default_rng(self.base_seed + 100000000)
        self.phase_rng = np.random.default_rng(self.base_seed + 200000000)
        self.service_rng = np.random.default_rng(self.base_seed + 300000000)
        state = super().reset()
        assert self.state is not None
        self.phase_history = [self.state.phase.copy()]
        return state

    def _advance_map_phases(self) -> None:
        """Advance the policy-independent phase stream shared across regimes."""
        assert self.state is not None
        for queue, Q in enumerate(self.problem.arrival_Q):
            current = int(self.state.phase[queue])
            departure_rate = float(-Q[current, current])
            if departure_rate <= 0.0:
                continue
            if self.phase_rng.random() >= 1.0 - math.exp(-departure_rate * self.dt):
                continue
            probabilities = np.maximum(Q[current].copy(), 0.0)
            probabilities[current] = 0.0
            probabilities /= probabilities.sum()
            self.state.phase[queue] = int(self.phase_rng.choice(len(probabilities), p=probabilities))

    def _physical_step(self, action: np.ndarray) -> Dict[str, float]:
        """Step with arrival/phase streams independent of policy actions."""
        assert self.state is not None
        problem = self.problem
        state = self.state
        action = np.asarray(action, dtype=int)
        if action.shape != (problem.K,):
            raise ValueError(f"action shape {action.shape}, expected {(problem.K,)}")

        switch_penalty = 0.0
        switches = 0
        for server in range(problem.K):
            desired = int(action[server]) - 1
            if desired >= 0 and not problem.compat[server, desired]:
                desired = -1
            if desired != int(state.assigned[server]):
                if desired >= 0 or int(state.assigned[server]) >= 0:
                    switch_penalty += float(problem.switch_cost[server])
                    switches += 1
                state.assigned[server] = desired
                state.cooldown[server] = int(problem.switch_lag[server])

        previous_queue = state.q.copy()
        service = np.zeros(problem.d, dtype=int)
        for server in range(problem.K):
            if state.cooldown[server] > 0:
                state.cooldown[server] -= 1
                continue
            queue = int(state.assigned[server])
            if queue < 0:
                continue
            mean = max(
                0.0,
                float(problem.servers[server] * problem.service_mu[server, queue] * self.dt),
            )
            if mean <= 0.0:
                continue
            coefficient_of_variation = max(0.05, float(problem.service_cv[server, queue]))
            if coefficient_of_variation <= 1.05:
                completion = self.service_rng.poisson(mean)
            else:
                shape = 1.0 / max(1e-6, coefficient_of_variation**2 - 1.0)
                scale = mean / shape
                completion = self.service_rng.poisson(self.service_rng.gamma(shape, scale))
            service[queue] += int(completion)

        rates = self.current_arrival_rates()
        arrivals = self.arrival_rng.poisson(np.maximum(0.0, rates * self.dt)).astype(int)
        self.last_arrivals_by_queue = arrivals.copy()
        self._advance_map_phases()
        served = np.minimum(previous_queue, service)
        uncapped_queue = previous_queue - served + arrivals
        assert problem.buffer_cap is not None
        dropped = np.maximum(0, uncapped_queue - problem.buffer_cap)
        state.q = np.clip(uncapped_queue, 0, problem.buffer_cap).astype(int)
        overflow = float(np.any(state.q >= problem.buffer_cap))
        cap_queue_fraction = float(np.mean(state.q >= problem.buffer_cap))
        in_service = np.zeros(problem.d, dtype=float)
        for server in range(problem.K):
            queue = int(state.assigned[server])
            if queue >= 0 and state.cooldown[server] == 0:
                in_service[queue] += problem.servers[server]
        waiting = np.maximum(0.0, state.q.astype(float) - in_service)
        return {
            "total_queue": float(state.q.sum()),
            "waiting_queue": float(waiting.sum()),
            "switch_penalty": float(switch_penalty),
            "switches": float(switches),
            "arrivals": float(arrivals.sum()),
            "admitted_arrivals": float(arrivals.sum() - dropped.sum()),
            "dropped_arrivals": float(dropped.sum()),
            "served": float(served.sum()),
            "overflow": overflow,
            "cap_queue_fraction": cap_queue_fraction,
        }

    def step(self, action: np.ndarray) -> Dict[str, float]:
        info = self._physical_step(action)
        assert self.state is not None
        self.phase_history.append(self.state.phase.copy())
        keep = max(2, self.regime.delay + 2)
        if len(self.phase_history) > keep:
            self.phase_history = self.phase_history[-keep:]
        return info

    def _belief(self, queue: int) -> np.ndarray:
        assert self.state is not None
        n = len(self.problem.arrival_rates[queue])
        if self.regime.kind == "stationary":
            return self.stationary[queue].copy()
        if self.regime.kind == "delay":
            history_index = max(0, len(self.phase_history) - 1 - self.regime.delay)
            phase = int(self.phase_history[history_index][queue])
        else:
            phase = int(self.state.phase[queue])
        belief = np.zeros(n, dtype=float)
        belief[phase] = 1.0
        if self.regime.kind == "posterior":
            epsilon = float(self.regime.contamination)
            belief = (1.0 - epsilon) * belief + epsilon * self.stationary[queue]
        return belief

    def forecast_arrival_excess(self, horizon: int = 6) -> np.ndarray:
        if self.regime.kind == "oracle":
            return super().forecast_arrival_excess(horizon)
        out = np.zeros(self.problem.d, dtype=float)
        for queue, (rates, Q) in enumerate(zip(self.problem.arrival_rates, self.problem.arrival_Q)):
            transition = self._transition_matrix(Q)
            distribution = self._belief(queue)
            expected = 0.0
            for _ in range(max(1, horizon)):
                expected += float(distribution @ rates) * self.dt
                distribution = distribution @ transition
            baseline = float(self.problem.arrival_mean[queue]) * self.dt * max(1, horizon)
            out[queue] = max(0.0, expected - baseline)
        return out


def parse_regime(raw: str) -> ObservationRegime:
    name = raw.strip()
    if name == "oracle":
        return ObservationRegime(name, "oracle")
    if name == "stationary":
        return ObservationRegime(name, "stationary")
    if name.startswith("posterior_"):
        epsilon = float(name.split("_", 1)[1])
        if not 0.0 <= epsilon <= 1.0:
            raise ValueError(f"posterior contamination must lie in [0,1]: {name}")
        return ObservationRegime(name, "posterior", contamination=epsilon)
    if name.startswith("delay_"):
        delay = int(name.split("_", 1)[1])
        if delay < 0:
            raise ValueError(f"delay must be nonnegative: {name}")
        return ObservationRegime(name, "delay", delay=delay)
    raise ValueError(f"unknown observation regime: {name}")


def select_cases(case_ids: Sequence[str]) -> List[CaseSpec]:
    cases = policy_cases(RunConfig(output_dir="", families=("A2_map_burst",)))
    by_id = {case.case_id: case for case in cases}
    missing = [case_id for case_id in case_ids if case_id not in by_id]
    if missing:
        raise ValueError("unknown A2 case ids: " + ", ".join(missing))
    return [by_id[case_id] for case_id in case_ids]


def summarize(replications: Sequence[Dict[str, object]]) -> tuple[List[Dict[str, object]], List[Dict[str, object]]]:
    oracle = {
        (str(row["case_id"]), int(row["replication"])): row
        for row in replications
        if row["observation_regime"] == "oracle"
    }
    groups: Dict[tuple[str, str], List[Dict[str, object]]] = {}
    for row in replications:
        groups.setdefault((str(row["case_id"]), str(row["observation_regime"])), []).append(row)

    case_rows: List[Dict[str, object]] = []
    for (case_id, regime), rows in sorted(groups.items()):
        result: Dict[str, object] = {"case_id": case_id, "observation_regime": regime, "n": len(rows)}
        for metric in ("objective", "mean_total_queue", "mean_switch_cost", "switch_rate"):
            stats = mean_ci(float(row[metric]) for row in rows)
            result.update({f"{metric}_{name}": value for name, value in stats.items()})
        gaps = [
            float(row["objective"]) - float(oracle[(case_id, int(row["replication"]))]["objective"])
            for row in rows
        ]
        gap_stats = mean_ci(gaps)
        result.update({f"paired_objective_gap_{name}": value for name, value in gap_stats.items()})
        case_rows.append(result)

    overall_rows: List[Dict[str, object]] = []
    regimes = sorted({str(row["observation_regime"]) for row in replications})
    for regime in regimes:
        rows = [row for row in replications if row["observation_regime"] == regime]
        by_replication: Dict[int, List[float]] = {}
        for row in rows:
            key = (str(row["case_id"]), int(row["replication"]))
            gap = float(row["objective"]) - float(oracle[key]["objective"])
            by_replication.setdefault(int(row["replication"]), []).append(gap)
        equally_weighted_gaps = [float(np.mean(values)) for values in by_replication.values()]
        stats = mean_ci(equally_weighted_gaps)
        overall_rows.append({
            "observation_regime": regime,
            "case_count": len({str(row["case_id"]) for row in rows}),
            "replications": len(by_replication),
            **{f"equal_case_weight_paired_objective_gap_{name}": value for name, value in stats.items()},
        })
    return case_rows, overall_rows


def plot_results(case_rows: Sequence[Dict[str, object]], output_path: str) -> None:
    cases = list(dict.fromkeys(str(row["case_id"]) for row in case_rows))
    regimes = list(dict.fromkeys(str(row["observation_regime"]) for row in case_rows))
    x = np.arange(len(cases), dtype=float)
    width = 0.82 / max(1, len(regimes))
    fig, ax = plt.subplots(figsize=(10.5, 4.8), constrained_layout=True)
    colors = plt.get_cmap("viridis")(np.linspace(0.12, 0.88, len(regimes)))
    lookup = {(str(row["case_id"]), str(row["observation_regime"])): row for row in case_rows}
    for index, (regime, color) in enumerate(zip(regimes, colors)):
        values = [float(lookup[(case, regime)]["paired_objective_gap_mean"]) for case in cases]
        errors = [float(lookup[(case, regime)]["paired_objective_gap_ci95"]) for case in cases]
        ax.bar(
            x + (index - (len(regimes) - 1) / 2) * width,
            values,
            width,
            yerr=errors,
            capsize=2,
            color=color,
            label=regime.replace("_", " "),
        )
    ax.axhline(0.0, color=PAPER_COLORS["text"], linewidth=1.0)
    ax.set_xticks(x)
    ax.set_xticklabels([case.replace("_", " ") for case in cases], rotation=25, ha="right")
    ax.set_ylabel("Paired standardized-objective gap vs oracle phase")
    ax.grid(axis="y", alpha=0.25)
    ax.legend(frameon=False, ncol=4, fontsize=8)
    fig.savefig(output_path, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description="gPAH robustness to imperfect MMPP-phase observations.")
    parser.add_argument("--output-dir", "--output_dir", dest="output_dir", required=True)
    parser.add_argument("--case-ids", default=",".join(DEFAULT_CASE_IDS))
    parser.add_argument("--regimes", default=DEFAULT_REGIMES)
    parser.add_argument("--replications", type=int, default=30)
    parser.add_argument("--warmup-steps", type=int, default=500)
    parser.add_argument("--eval-steps", type=int, default=3000)
    parser.add_argument("--seed", type=int, default=30260527)
    args = parser.parse_args()

    case_ids = tuple(item.strip() for item in args.case_ids.split(",") if item.strip())
    regimes = [parse_regime(item) for item in args.regimes.split(",") if item.strip()]
    if not any(regime.kind == "oracle" for regime in regimes):
        raise ValueError("--regimes must include oracle for paired comparisons")
    cases = select_cases(case_ids)
    os.makedirs(args.output_dir, exist_ok=True)

    rep_rows: List[Dict[str, object]] = []
    total = len(cases) * len(regimes) * args.replications
    done = 0
    for case_index, case in enumerate(cases, 1):
        problem = make_problem(case, args.seed + 1009 * case_index)
        for replication in range(args.replications):
            simulation_seed = args.seed + 100000 * case_index + replication
            for regime in regimes:
                env = BeliefForecastEnv(problem, simulation_seed, regime)
                env.reset()
                policy = policy_from_name("gpah")
                policy.reset(problem)
                metrics = simulate_policy_object(
                    problem,
                    policy,
                    env,
                    args.warmup_steps,
                    args.eval_steps,
                )
                rep_rows.append({
                    "experiment": "phase_observation_robustness",
                    "family": case.family,
                    "case_id": case.case_id,
                    "map_profile": case.map_profile,
                    "observation_regime": regime.name,
                    "observation_kind": regime.kind,
                    "posterior_contamination": regime.contamination,
                    "phase_delay_steps": regime.delay,
                    "policy": "gpah",
                    "replication": replication,
                    "seed": simulation_seed,
                    **metrics,
                })
                done += 1
                render_progress(done, total, f"{case.case_id} {regime.name}")

    case_rows, overall_rows = summarize(rep_rows)
    write_csv(os.path.join(args.output_dir, "paper1_phase_observation_replications.csv"), rep_rows)
    write_csv(os.path.join(args.output_dir, "paper1_phase_observation_case_summary.csv"), case_rows)
    write_csv(os.path.join(args.output_dir, "paper1_phase_observation_overall_summary.csv"), overall_rows)
    plot_results(case_rows, os.path.join(args.output_dir, "fig_phase_observation_robustness.pdf"))
    manifest = {
        "experiment": "phase_observation_robustness",
        "case_ids": list(case_ids),
        "regimes": [regime.__dict__ for regime in regimes],
        "replications": args.replications,
        "warmup_steps": args.warmup_steps,
        "eval_steps": args.eval_steps,
        "seed": args.seed,
        "paired_design": "identical initial state, arrival stream, and phase stream across observation regimes",
        "random_stream_isolation": "arrival and phase streams are independent of policy-dependent service draws",
    }
    with open(os.path.join(args.output_dir, "run_manifest.json"), "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=2)
    print(f"Phase-observation robustness results: {args.output_dir}", flush=True)


if __name__ == "__main__":
    main()
