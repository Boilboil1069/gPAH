#!/usr/bin/env python3
"""Reanalyse completed policy replications with families as equal-weight blocks.

The analysis is deterministic and runs no simulator.  Replications are first
paired within each case, policy means are then formed for the case, relative
gPAH effects are averaged equally across cases within a family, and the eight
family effects are finally averaged with equal family weight.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import statistics
from collections import defaultdict
from pathlib import Path


COMPARATORS = ("maxweight_mu", "affinity", "qah_switch", "gpah_meanmap")
POLICY_LABELS = {
    "maxweight_mu": "MaxWeight-$\\mu$",
    "affinity": "GB-PANDAS-style",
    "qah_switch": "QAH+Switch",
    "gpah_meanmap": "gPAH-StationaryMean",
}
FAMILY_LABELS = {
    "A1_topology": "A1 topology",
    "A2_map_burst": "A2 MMPP regime",
    "A3_density": "A3 compatibility density",
    "A4_service": "A4 service heterogeneity",
    "A5_switch": "A5 switching friction",
    "A6_scale": "A6 moderate scale",
    "A7_load": "A7 offered load",
    "A8_large_scale": "A8 large scale",
}
METRICS = ("objective", "mean_total_queue")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/raw/final_run/policy/paper1_policy_replications.csv"),
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("data/derived/family_blocked_reanalysis"),
    )
    parser.add_argument("--target-policy", default="gpah")
    parser.add_argument("--expected-replications", type=int, default=50)
    return parser.parse_args()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_csv(path: Path, rows: list[dict[str, object]], fields: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def relative_improvement(baseline: float, target: float) -> float:
    if baseline == 0:
        raise ValueError("A zero comparator mean makes the relative effect undefined")
    return 100.0 * (baseline - target) / abs(baseline)


def render_tex(family_rows: list[dict[str, object]], overall_rows: list[dict[str, object]]) -> str:
    by_family = {(str(r["family"]), str(r["comparator"])): r for r in family_rows}
    by_comparator = {str(r["comparator"]): r for r in overall_rows}
    lines = [
        "% Generated by experiment/reanalyze_gpah_paper1_family_blocked.py",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Family block & MaxWeight-$\\mu$ & GB-PANDAS-style & QAH+Switch & gPAH-StationaryMean \\\\",
        "\\midrule",
    ]
    for family in FAMILY_LABELS:
        values = [float(by_family[(family, comparator)]["objective_improvement_pct"]) for comparator in COMPARATORS]
        lines.append(FAMILY_LABELS[family] + " & " + " & ".join(f"{v:.1f}\\%" for v in values) + " \\\\")
    lines.extend(["\\midrule"])
    values = [float(by_comparator[c]["objective_equal_family_mean_pct"]) for c in COMPARATORS]
    lines.append("Equal-family mean & " + " & ".join(f"{v:.1f}\\%" for v in values) + " \\\\")
    values = [int(by_comparator[c]["families_improved"]) for c in COMPARATORS]
    lines.append("Families improved & " + " & ".join(f"{v}/8" for v in values) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    return "\n".join(lines)


def main() -> None:
    args = parse_args()
    input_path = args.input.resolve()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    selected = set(COMPARATORS) | {args.target_policy}
    values: dict[tuple[str, str, str, int], dict[str, float]] = {}
    with input_path.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            policy = row["policy"]
            if policy not in selected:
                continue
            key = (row["family"], row["case_id"], policy, int(row["replication"]))
            if key in values:
                raise ValueError(f"Duplicate family/case/policy/replication row: {key}")
            values[key] = {metric: float(row[metric]) for metric in METRICS}

    families = sorted({key[0] for key in values})
    if families != list(FAMILY_LABELS):
        raise ValueError(f"Unexpected family set or ordering: {families}")

    cases_by_family: dict[str, set[str]] = defaultdict(set)
    for family, case_id, _, _ in values:
        cases_by_family[family].add(case_id)

    case_rows: list[dict[str, object]] = []
    for family in FAMILY_LABELS:
        for case_id in sorted(cases_by_family[family]):
            target_reps = {
                rep for fam, case, policy, rep in values
                if fam == family and case == case_id and policy == args.target_policy
            }
            expected = set(range(args.expected_replications))
            if target_reps != expected:
                raise ValueError(f"Incomplete target replications for {family}/{case_id}")
            for comparator in COMPARATORS:
                comparator_reps = {
                    rep for fam, case, policy, rep in values
                    if fam == family and case == case_id and policy == comparator
                }
                if comparator_reps != target_reps:
                    raise ValueError(f"Unpaired replications for {family}/{case_id}/{comparator}")
                record: dict[str, object] = {
                    "family": family,
                    "family_label": FAMILY_LABELS[family],
                    "case_id": case_id,
                    "comparator": comparator,
                    "comparator_label": POLICY_LABELS[comparator].replace("$\\mu$", "mu"),
                    "replications": len(target_reps),
                }
                for metric in METRICS:
                    baseline = statistics.fmean(values[(family, case_id, comparator, rep)][metric] for rep in target_reps)
                    target = statistics.fmean(values[(family, case_id, args.target_policy, rep)][metric] for rep in target_reps)
                    prefix = "objective" if metric == "objective" else "queue"
                    record[f"{prefix}_comparator_mean"] = baseline
                    record[f"{prefix}_gpah_mean"] = target
                    record[f"{prefix}_improvement_pct"] = relative_improvement(baseline, target)
                case_rows.append(record)

    family_rows: list[dict[str, object]] = []
    for family in FAMILY_LABELS:
        for comparator in COMPARATORS:
            selected_rows = [r for r in case_rows if r["family"] == family and r["comparator"] == comparator]
            family_rows.append({
                "family": family,
                "family_label": FAMILY_LABELS[family],
                "comparator": comparator,
                "comparator_label": POLICY_LABELS[comparator].replace("$\\mu$", "mu"),
                "cases": len(selected_rows),
                "case_wins": sum(float(r["objective_improvement_pct"]) > 0 for r in selected_rows),
                "objective_improvement_pct": statistics.fmean(float(r["objective_improvement_pct"]) for r in selected_rows),
                "queue_improvement_pct": statistics.fmean(float(r["queue_improvement_pct"]) for r in selected_rows),
            })

    overall_rows: list[dict[str, object]] = []
    for comparator in COMPARATORS:
        selected_families = [r for r in family_rows if r["comparator"] == comparator]
        selected_cases = [r for r in case_rows if r["comparator"] == comparator]
        objective_effects = [float(r["objective_improvement_pct"]) for r in selected_families]
        queue_effects = [float(r["queue_improvement_pct"]) for r in selected_families]
        overall_rows.append({
            "comparator": comparator,
            "comparator_label": POLICY_LABELS[comparator].replace("$\\mu$", "mu"),
            "families": len(selected_families),
            "families_improved": sum(value > 0 for value in objective_effects),
            "cases": len(selected_cases),
            "case_wins": sum(float(r["objective_improvement_pct"]) > 0 for r in selected_cases),
            "objective_equal_family_mean_pct": statistics.fmean(objective_effects),
            "objective_family_sd_pct": statistics.stdev(objective_effects),
            "objective_family_min_pct": min(objective_effects),
            "objective_family_max_pct": max(objective_effects),
            "queue_equal_family_mean_pct": statistics.fmean(queue_effects),
            "queue_family_sd_pct": statistics.stdev(queue_effects),
            "queue_family_min_pct": min(queue_effects),
            "queue_family_max_pct": max(queue_effects),
        })

    case_fields = list(case_rows[0])
    family_fields = list(family_rows[0])
    overall_fields = list(overall_rows[0])
    write_csv(output_dir / "paper1_family_blocked_case_effects.csv", case_rows, case_fields)
    write_csv(output_dir / "paper1_family_blocked_family_effects.csv", family_rows, family_fields)
    write_csv(output_dir / "paper1_family_blocked_overall.csv", overall_rows, overall_fields)
    (output_dir / "tab_family_blocked_effects.tex").write_text(render_tex(family_rows, overall_rows), encoding="utf-8")

    manifest = {
        "analysis": "family-blocked reanalysis of completed replications",
        "input": str(args.input),
        "input_sha256": sha256(input_path),
        "target_policy": args.target_policy,
        "comparators": list(COMPARATORS),
        "expected_replications_per_case_policy": args.expected_replications,
        "hierarchy": [
            "verify paired replication IDs within each case",
            "average replications to one mean per case and policy",
            "compute gPAH relative improvement for each case",
            "average case effects equally within each family",
            "average the eight family effects with equal family weight",
        ],
        "primary_metric": "standardized objective",
        "secondary_metric": "mean total queue length",
        "family_count": len(FAMILY_LABELS),
        "case_count": sum(len(cases) for cases in cases_by_family.values()),
    }
    (output_dir / "run_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    for row in overall_rows:
        print(
            f"{row['comparator_label']}: objective={row['objective_equal_family_mean_pct']:.3f}% "
            f"({row['families_improved']}/8 families), queue={row['queue_equal_family_mean_pct']:.3f}%"
        )
    print(f"Wrote {output_dir}")


if __name__ == "__main__":
    main()
